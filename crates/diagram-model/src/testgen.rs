//! Test support (S-043 / ADR 018): replay *sequences of operations* against a live
//! [`Diagram`] and check the aggregate's invariants.
//!
//! This module exists so every crate's property tests can drive the model through the same
//! operation vocabulary (place/move/resize/remove, connect, attach/detach endpoints, bends,
//! tips, scale, colors) without duplicating the replay logic. It is test support only —
//! production code must not depend on it. No extra dependencies: plain model types.

use std::collections::BTreeSet;

use crate::{
    ColorRole, Diagram, Rgb,
    anchors::{AnchorRef, ConnectorEndpoint},
    geometry::{CellPos, CellSize},
    invariants::ModelError,
    objects::{
        ConnectorEnd, ConnectorInstance, ConnectorStyle, Object, ObjectId, ShapeInstance,
        TextInstance, TipStyle,
    },
};

/// Operation descriptors generated by test strategies and replayed against a *live* diagram.
///
/// Objects are referenced by index into the current aggregate (shapes / connectors / all
/// objects). An out-of-range index is deliberately not skipped: it is resolved to an id that
/// cannot exist, so error paths (`UnknownObject` & co.) are exercised too.
#[derive(Debug, Clone)]
pub enum Op {
    /// Place a shape at `(x, y)` with size `(w, h)`; 0 sizes are rejected by the model.
    PlaceShape {
        x: u32,
        y: u32,
        w: u32,
        h: u32,
    },
    /// Place a text object (occasionally with empty content — rejected).
    PlaceText {
        x: u32,
        y: u32,
        empty: bool,
    },
    /// Move the shape at `shape_index` to `(x, y)`.
    Move {
        shape_index: usize,
        x: u32,
        y: u32,
    },
    /// Resize the shape at `shape_index`; 0 sizes are rejected.
    Resize {
        shape_index: usize,
        w: u32,
        h: u32,
    },
    /// Remove the object at `object_index`.
    Remove {
        object_index: usize,
    },
    /// Connect two shapes (anchors may be unknown to the registry — the model does not check it).
    Connect {
        a: usize,
        b: usize,
        anchor_a: &'static str,
        anchor_b: &'static str,
    },
    /// Attach one end of the connector at `conn_index` to a shape anchor.
    AttachEnd {
        conn_index: usize,
        end: u8,
        shape_index: usize,
        anchor: &'static str,
    },
    /// Detach one end of the connector at `conn_index` to a free cell.
    FreeEnd {
        conn_index: usize,
        end: u8,
        x: u32,
        y: u32,
    },
    AddBend {
        conn_index: usize,
        index: usize,
        x: u32,
        y: u32,
    },
    MoveBend {
        conn_index: usize,
        index: usize,
        x: u32,
        y: u32,
    },
    RemoveBend {
        conn_index: usize,
        index: usize,
    },
    SetTip {
        conn_index: usize,
        end: u8,
        style: u8,
    },
    /// `scale` is drawn from 0..=9 so the rejection of 0 (`ScaleTooSmall`) is covered.
    SetScale {
        scale: u32,
    },
    SetColor {
        role: u8,
        set: bool,
        r: u8,
        g: u8,
        b: u8,
    },
}

/// Anchor names used by generated operations: the box anchors plus a token the shape
/// registry does not know (the model accepts any single-token anchor name).
pub const ANCHORS: &[&str] = &["n", "s", "w", "e", "weird-anchor"];

/// `ObjectId::generated(UNKNOWN_ID)` can never exist in a diagram built by [`replay`].
const UNKNOWN_ID: u32 = 999_999;

fn object_id(n: u32) -> ObjectId {
    ObjectId::generated(n)
}

fn shape_at(d: &Diagram, index: usize) -> Option<ObjectId> {
    d.objects().iter().enumerate().find_map(|(i, o)| match o {
        Object::Shape(s) if i == index => Some(s.id.clone()),
        _ => None,
    })
}

fn connector_at(d: &Diagram, index: usize) -> Option<ObjectId> {
    d.objects().iter().enumerate().find_map(|(i, o)| match o {
        Object::Connector(c) if i == index => Some(c.id.clone()),
        _ => None,
    })
}

fn object_at(d: &Diagram, index: usize) -> Option<ObjectId> {
    d.objects().get(index).map(|o| o.id().clone())
}

/// Applies one operation to the live diagram. `Ok(())` = the model accepted it; a rejected
/// operation leaves the diagram unchanged (that itself is a property under test).
pub fn apply(d: &mut Diagram, op: &Op) -> Result<(), ModelError> {
    let unknown = object_id(UNKNOWN_ID);
    match op {
        Op::PlaceShape { x, y, w, h } => d.place_shape(ShapeInstance::new(
            d.new_object_id(),
            "box",
            "",
            CellPos::new(*x, *y),
            CellSize::new(*w, *h)?,
        )?),
        Op::PlaceText { x, y, empty } => d.place_text(TextInstance::new(
            d.new_object_id(),
            CellPos::new(*x, *y),
            if *empty { "" } else { "t" },
        )?),
        Op::Move { shape_index, x, y } => d.move_object(
            &shape_at(d, *shape_index).unwrap_or(unknown),
            CellPos::new(*x, *y),
        ),
        Op::Resize { shape_index, w, h } => d.resize(
            &shape_at(d, *shape_index).unwrap_or(unknown),
            CellSize::new(*w, *h)?,
        ),
        Op::Remove { object_index } => d
            .remove(&object_at(d, *object_index).unwrap_or(unknown))
            .map(|_| ()),
        Op::Connect {
            a,
            b,
            anchor_a,
            anchor_b,
        } => match (shape_at(d, *a), shape_at(d, *b)) {
            // Both shapes present: real attach-attach connect. Otherwise fall back to a
            // standalone free-end connector so the operation still exercises the aggregate
            // (and hits ZeroLengthConnector when both free ends share a cell).
            (Some(fa), Some(fb)) => d.connect(ConnectorInstance::between(
                d.new_object_id(),
                AnchorRef::new(fa, anchor_a)?,
                AnchorRef::new(fb, anchor_b)?,
                ConnectorStyle::default(),
            )),
            _ => d.connect(ConnectorInstance::new(
                d.new_object_id(),
                ConnectorEndpoint::Free(CellPos::new(0, 0)),
                ConnectorEndpoint::Free(CellPos::new(1, 1)),
                ConnectorStyle::default(),
            )),
        },
        Op::AttachEnd {
            conn_index,
            end,
            shape_index,
            anchor,
        } => {
            let cid = connector_at(d, *conn_index).unwrap_or(unknown);
            match shape_at(d, *shape_index) {
                Some(sid) => d.set_endpoint(
                    &cid,
                    end_of(*end),
                    ConnectorEndpoint::Attached(AnchorRef::new(sid, anchor)?),
                ),
                None => d.set_endpoint(
                    &cid,
                    end_of(*end),
                    ConnectorEndpoint::Free(CellPos::new(0, 0)),
                ),
            }
        }
        Op::FreeEnd {
            conn_index,
            end,
            x,
            y,
        } => d.set_endpoint(
            &connector_at(d, *conn_index).unwrap_or(unknown),
            end_of(*end),
            ConnectorEndpoint::Free(CellPos::new(*x, *y)),
        ),
        Op::AddBend {
            conn_index,
            index,
            x,
            y,
        } => d.add_bend(
            &connector_at(d, *conn_index).unwrap_or(unknown),
            *index,
            CellPos::new(*x, *y),
        ),
        Op::MoveBend {
            conn_index,
            index,
            x,
            y,
        } => d.move_bend(
            &connector_at(d, *conn_index).unwrap_or(unknown),
            *index,
            CellPos::new(*x, *y),
        ),
        Op::RemoveBend { conn_index, index } => {
            d.remove_bend(&connector_at(d, *conn_index).unwrap_or(unknown), *index)
        }
        Op::SetTip {
            conn_index,
            end,
            style,
        } => d.set_tip(
            &connector_at(d, *conn_index).unwrap_or(unknown),
            end_of(*end),
            tip_of(*style),
        ),
        Op::SetScale { scale } => d.set_scale(*scale),
        Op::SetColor { role, set, r, g, b } => {
            d.set_color(
                role_of(*role),
                if *set {
                    Some(Rgb::new(*r, *g, *b))
                } else {
                    None
                },
            );
            Ok(())
        }
    }
}

fn end_of(n: u8) -> ConnectorEnd {
    if n.is_multiple_of(2) {
        ConnectorEnd::Source
    } else {
        ConnectorEnd::Target
    }
}

fn tip_of(n: u8) -> TipStyle {
    match n % 4 {
        0 => TipStyle::Bare,
        1 => TipStyle::HollowArrow,
        2 => TipStyle::EmptyRhombus,
        _ => TipStyle::FilledRhombus,
    }
}

fn role_of(n: u8) -> ColorRole {
    match n % 3 {
        0 => ColorRole::LineText,
        1 => ColorRole::Fill,
        _ => ColorRole::Background,
    }
}

/// Replays a sequence of operations on a fresh diagram. Rejected operations are legal
/// inputs — the model refused them; the aggregate stays consistent either way.
#[must_use]
pub fn replay(ops: &[Op]) -> Diagram {
    let mut d = Diagram::new();
    for op in ops {
        if apply(&mut d, op).is_err() {
            // Rejected on purpose — see the module docs.
        }
    }
    d
}

/// The model invariants every well-formed aggregate must satisfy:
/// unique ids; connector endpoints reference existing shapes; no zero-length (both-free-at-one-cell)
/// connectors; positive shape sizes; scale ≥ 1; non-empty text.
///
/// Returns one message per violation — empty means the diagram is consistent.
#[must_use]
pub fn invariant_violations(d: &Diagram) -> Vec<String> {
    let mut violations = Vec::new();

    // Unique object ids.
    let mut seen = BTreeSet::new();
    for o in d.objects() {
        if !seen.insert(o.id().clone()) {
            violations.push(format!("duplicate id {}", o.id()));
        }
    }

    // Referential integrity + zero-length rule for connectors.
    let shape_ids: BTreeSet<&ObjectId> = d
        .objects()
        .iter()
        .filter_map(|o| match o {
            Object::Shape(s) => Some(&s.id),
            _ => None,
        })
        .collect();
    for o in d.objects() {
        if let Object::Connector(c) = o {
            for endpoint in [c.from.clone(), c.to.clone()] {
                if let ConnectorEndpoint::Attached(ref anchor) = endpoint
                    && !shape_ids.contains(&anchor.object)
                {
                    violations.push(format!(
                        "connector {} references missing object {}",
                        c.id, anchor.object
                    ));
                }
            }
            match (&c.from, &c.to) {
                (ConnectorEndpoint::Free(a), ConnectorEndpoint::Free(b)) if a == b => {
                    violations.push(format!("zero-length connector {}", c.id));
                }
                _ => {}
            }
        }
    }

    // Positive sizes; scale ≥ 1; non-empty text.
    for o in d.objects() {
        match o {
            Object::Shape(s) if s.size.width < 1 || s.size.height < 1 => {
                violations.push(format!("shape {} has a non-positive size", s.id));
            }
            Object::Text(t) if t.text.is_empty() => {
                violations.push(format!("text {} is empty", t.id));
            }
            _ => {}
        }
    }
    if d.scale() < 1 {
        violations.push(format!("scale {} below 1", d.scale()));
    }
    violations
}
